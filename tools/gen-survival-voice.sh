#!/usr/bin/env bash
# Generate the survival announcer pack ("Morpheus") with VoxCPM2 on spark.
#
#   tools/gen-survival-voice.sh --design [n]   # roll n voice designs into /tmp/morpheus-design
#   tools/gen-survival-voice.sh                # clone every line in lines.tsv from the kept ref
#
# Same discipline as the hero packs (tools/gen-erikson-voice.sh): the voice is
# DESIGNED once, the best roll kept as _ref/morpheus_ref.wav (in the repo — the
# pack is only reproducible because of it), and every line CLONED from it.
# Post-FX: 7 % pitch-down and a large-hall reverb — a voice from everywhere.
#
# Raw takes -> assets/work/survival/voice/_raw_tts/<stem>.wav
# Runtime   -> public/assets/survival/voice/<stem>.webm (Opus 24k mono, -23 LUFS)
# Idempotent: existing raw takes are skipped; delete one to re-roll that line.
# `--subtitles` only rewrites src/survival/voiceLines.ts from lines.tsv.
# An optional 5th column pins the seed (a re-roll that QA kept).
set -euo pipefail
cd "$(dirname "$0")/.."

API="${VOXCPM_API:-http://localhost:8647/v1/audio/speech}"
MODEL="openbmb/VoxCPM2"
WORK=assets/work/survival/voice
RAW=$WORK/_raw_tts
OUT=public/assets/survival/voice
REF=$WORK/_ref/morpheus_ref.wav
mkdir -p "$RAW" "$OUT"

seed_for() { python3 -c 'import zlib,sys; print(3000 + zlib.crc32(sys.argv[1].encode()) % 10000)' "$1"; }

speak() { # out text seed [ref]
  python3 - "$MODEL" "$2" "$3" "${4:-}" <<'PY' | curl -sf -m 600 -X POST "$API" \
      -H 'Content-Type: application/json' -d @- --output "$1"
import base64, json, sys
model, text, seed, ref = sys.argv[1:5]
body = {"model": model, "input": text, "voice": "default", "response_format": "wav", "seed": int(seed)}
if ref:
    body["ref_audio"] = "data:audio/wav;base64," + base64.b64encode(open(ref, "rb").read()).decode()
print(json.dumps(body))
PY
}

if [ "${1:-}" = "--design" ]; then
  n="${2:-4}"; dir=/tmp/morpheus-design; mkdir -p "$dir"
  prompt="$(tr '\n' ' ' < "$WORK/_ref/DESIGN_PROMPT.txt" | sed 's/ *$//')"
  for i in $(seq 1 "$n"); do
    echo "== design roll $i"
    speak "$dir/roll_$((2000 + i)).wav" "($prompt)$(cat "$WORK/_ref/morpheus_ref.txt")" $((2000 + i))
  done
  ls -1 "$dir"; exit 0
fi

if [ "${1:-}" = "--subtitles" ]; then SUBS_ONLY=1; else SUBS_ONLY=0; fi
[ "$SUBS_ONLY" = 1 ] || [ -s "$REF" ] || { echo "no $REF — run --design, audition, keep a roll first" >&2; exit 1; }

STYLE="Ancient god of dreams, deep resonant bass, slow and majestic"
FX="aresample=24000,asetrate=24000*0.93,aresample=24000,atempo=1.15,\
aecho=0.8:0.85:23|41|67:0.35|0.28|0.2,\
aecho=0.85:0.75:90|160|260|380|520:0.32|0.25|0.19|0.14|0.1"

[ "$SUBS_ONLY" = 1 ] || grep -v '^#' "$WORK/lines.tsv" | while IFS=$'\t' read -r stem cat text delivery seed; do
  [ -n "$stem" ] || continue
  if [ -s "$RAW/$stem.wav" ]; then echo "skip $stem"; else
    echo "== $stem"
    speak "$RAW/$stem.wav" "($STYLE, $delivery)$text" "${seed:-$(seed_for "$stem")}" "$REF"
  fi
  # Trim lead-in air to 60 ms, pitch/reverb, level to -23 LUFS.
  ffmpeg -y -loglevel error -i "$RAW/$stem.wav" \
    -af "silenceremove=start_periods=1:start_threshold=-40dB:start_silence=0.06,$FX,loudnorm=I=-23:TP=-3:LRA=11" \
    -codec:a libopus -b:a 24k -ac 1 -application voip "$OUT/$stem.webm"
done
# Subtitles: the same text the lines were recorded from (src/survival/announcer.ts).
python3 - "$WORK/lines.tsv" src/survival/voiceLines.ts <<'PY2'
import json, sys
rows = [l.rstrip("\n").split("\t") for l in open(sys.argv[1]) if l.strip() and not l.startswith("#")]
body = ",\n".join(f"  {r[0]}: {json.dumps(r[2], ensure_ascii=False)}" for r in rows)
open(sys.argv[2], "w").write(
    "// GENERATED by tools/gen-survival-voice.sh from assets/work/survival/voice/lines.tsv — do not edit.\n"
    "/** Morpheus subtitles: stem → the exact text the line was recorded from. */\n"
    f"export const VOICE_LINES: Record<string, string> = {{\n{body},\n}};\n")
PY2
echo "done: $(ls -1 "$OUT" | wc -l) lines"
