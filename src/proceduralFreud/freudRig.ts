export const FREUD_BONE_ORDER: readonly string[] = FREUD_JOINTS.map((j) => j.name);

export type FreudSkin = {
  vertexCount: number;
  skinIndex: Uint16Array;
  skinWeight: Float32Array;
};

/** Decode the baked 7-bytes-per-vertex stream (4 bone ids, 3 weight bytes; 4th weight is remainder). */
export function decodeSkin(base64: string, vertexCount: number): FreudSkin {
  let stream: Uint8Array;
  if (typeof atob === 'function') {
    const raw = atob(base64);
    stream = new Uint8Array(raw.length);
    for (let i = 0; i < raw.length; i += 1) stream[i] = raw.charCodeAt(i);
  } else {
    const buffer = (globalThis as { Buffer?: { from(s: string, e: string): Uint8Array } }).Buffer;
    if (!buffer) throw new Error('no base64 decoder available');
    stream = buffer.from(base64, 'base64');
  }
  if (stream.length !== vertexCount * 7) {
    throw new Error(`skin stream ${stream.length} bytes, expected ${vertexCount * 7}`);
  }
  const skinIndex = new Uint16Array(vertexCount * 4);
  const skinWeight = new Float32Array(vertexCount * 4);
  for (let i = 0; i < vertexCount; i += 1) {
    const at = i * 7;
    const w0 = stream[at + 4]; const w1 = stream[at + 5]; const w2 = stream[at + 6];
    const w3 = 255 - w0 - w1 - w2;
    for (let k = 0; k < 4; k += 1) skinIndex[i * 4 + k] = stream[at + k];
    /**
     * NORMALIZE, don't trust the byte sum. Independent rounding of w0..w2 can push the four-slot
     * total to 256/255, and at rest that blends to a 0.4% scale error -- the rest-pose gate measured
     * a 3.8 mm vertex shift at the head before this division existed.
     */
    const sum = w0 + w1 + w2 + Math.max(0, w3);
    if (sum > 0) {
      skinWeight[i * 4] = w0 / sum;
      skinWeight[i * 4 + 1] = w1 / sum;
      skinWeight[i * 4 + 2] = w2 / sum;
      skinWeight[i * 4 + 3] = Math.max(0, w3) / sum;
    } else {
      skinWeight[i * 4] = 1;
    }
  }
  return { vertexCount, skinIndex, skinWeight };
}

export type FreudRig = {
  skeleton: THREE.Skeleton;
  bones: Map<string, THREE.Bone>;
  root: THREE.Bone;
  boundMeshes: THREE.SkinnedMesh[];
};

/** Build just the bone hierarchy (no meshes) -- also what the FK sign verification drives. */
export function createFreudSkeleton(): { skeleton: THREE.Skeleton; bones: Map<string, THREE.Bone>; root: THREE.Bone } {
  const bones = new Map<string, THREE.Bone>();
  for (const joint of FREUD_JOINTS) {
    const bone = new THREE.Bone();
    bone.name = joint.name;
    bones.set(joint.name, bone);
  }
  // Positions are LOCAL to the parent, which is what a Bone expects.
  for (const joint of FREUD_JOINTS) {
    const bone = bones.get(joint.name)!;
    const parentJoint = joint.parent ? FREUD_JOINTS.find((j) => j.name === joint.parent)! : null;
    bone.position.set(
      joint.head[0] - (parentJoint?.head[0] ?? 0),
      joint.head[1] - (parentJoint?.head[1] ?? 0),
      joint.head[2] - (parentJoint?.head[2] ?? 0),
    );
    if (joint.parent) bones.get(joint.parent)!.add(bone);
  }
  const root = bones.get('hips')!;
  root.updateMatrixWorld(true);
  const skeleton = new THREE.Skeleton(FREUD_BONE_ORDER.map((n) => bones.get(n)!));
  return { skeleton, bones, root };
}

/**
 * Skin the figure's one merged mesh to the skeleton with the baked geodesic weights. Geometry is
 * authored in the source frame the bones are placed in, so the bind matrix is the identity.
 */
export function buildFreudRig(model: THREE.Object3D, skin: FreudSkin): FreudRig | null {
  const meshes: THREE.Mesh[] = [];
  model.traverse((o) => {
    const mesh = o as THREE.Mesh;
    if (mesh.isMesh && mesh.userData?.sdfSurface && mesh.geometry?.attributes?.position) {
      meshes.push(mesh);
    }
  });
  if (!meshes.length) return null;
  const { skeleton, bones, root } = createFreudSkeleton();
  const boundMeshes: THREE.SkinnedMesh[] = [];
  for (const mesh of meshes) {
    const count = mesh.geometry.attributes.position.count;
    if (count !== skin.vertexCount) {
      // Quality levels carry their own baked stream; a mismatch means the wrong one was decoded.
      console.warn(`[freud] skin stream has ${skin.vertexCount} vertices, mesh has ${count}; not rigging`);
      return null;
    }
    mesh.geometry.setAttribute('skinIndex', new THREE.BufferAttribute(skin.skinIndex, 4));
    mesh.geometry.setAttribute('skinWeight', new THREE.BufferAttribute(skin.skinWeight, 4));
    const skinned = new THREE.SkinnedMesh(mesh.geometry, mesh.material as THREE.Material);
    skinned.name = mesh.name;
    skinned.userData = mesh.userData;
    skinned.castShadow = mesh.castShadow;
    skinned.receiveShadow = mesh.receiveShadow;
    skinned.position.copy(mesh.position);
    skinned.quaternion.copy(mesh.quaternion);
    skinned.scale.copy(mesh.scale);
    const parent = mesh.parent!;
    parent.add(skinned);
    parent.remove(mesh);
    skinned.bind(skeleton, new THREE.Matrix4());
    boundMeshes.push(skinned);
  }
  model.add(root);
  return { skeleton, bones, root, boundMeshes };
}

/** Rest pose, captured once so `stop()` and the idle can return to exactly the built pose. */
export type RestPose = Map<string, THREE.Quaternion>;

export function captureRest(rig: FreudRig): RestPose {
  const rest: RestPose = new Map();
  for (const [name, bone] of rig.bones) rest.set(name, bone.quaternion.clone());
  return rest;
}

export function applyRest(rig: FreudRig, rest: RestPose): void {
  for (const [name, bone] of rig.bones) {
    const q = rest.get(name);
    if (q) bone.quaternion.copy(q);
  }
  rig.root.position.y = (rig.root.userData.restY as number | undefined) ?? rig.root.position.y;
  rig.root.updateMatrixWorld(true);
}

const EULER = new THREE.Euler();
const Q = new THREE.Quaternion();

/**
 * REAL GAIT CURVES, as a truncated Fourier series, because a walk is not a sine wave. The knee
 * flexes TWICE per stride -- a ~18-degree stance flexion after heel strike and a ~60-degree swing
 * flexion -- and a single-peak curve reads as a limp at any amplitude. Coefficients are the fit to
 * standard sagittal joint angles for adult level walking sampled every 5% of the cycle (four
 * harmonics: hip 0.27 deg, knee 0.89 deg, ankle 1.44 deg residual), the cited gait dataset the
 * standing rules allow; they are shared with the girl-character rig verbatim.
 */
type Harmonic = readonly [number, number];
type GaitCurve = { readonly dc: number; readonly h: readonly Harmonic[] };

const GAIT_HIP: GaitCurve = {
  dc: +0.20420,
  h: [[+0.33309, +0.02366], [-0.01022, -0.06826], [-0.00988, +0.01655], [+0.00457, +0.00000]],
};
const GAIT_KNEE: GaitCurve = {
  dc: +0.38572,
  h: [[-0.07829, -0.35537], [-0.20773, +0.18267], [+0.01966, +0.07181], [-0.01740, +0.00474]],
};
const GAIT_ANKLE: GaitCurve = {
  dc: -0.01571,
  h: [[-0.00172, +0.10605], [-0.02703, -0.13819], [+0.00560, +0.03738], [+0.02708, -0.02915]],
};

/** Evaluate a gait curve at a phase in [0,1). Radians. */
function gait(curve: GaitCurve, phase: number): number {
  let v = curve.dc;
  for (let i = 0; i < curve.h.length; i += 1) {
    const w = 2 * Math.PI * (i + 1) * phase;
    v += curve.h[i][0] * Math.cos(w) + curve.h[i][1] * Math.sin(w);
  }
  return v;
}

/** Smoothly saturate instead of introducing a hard kink into the periodic gait. */
const limitAngle = (value: number, limit: number): number =>
  limit * Math.tanh(value / limit);

/**
 * One stride of a human walk, in the SOURCE frame.
 *
 * SIGNS ARE DERIVED FOR THIS FRAME, not copied: bone local axes are world-aligned at bind, the limbs
 * point down (-Y) and the figure faces +X, so a POSITIVE rotation about Z swings a downward limb
 * toward +X -- FORWARD. Hip flexion is therefore +z, knee flexion (the shin trails) is -z, ankle
 * dorsiflexion +z. Verified by forward kinematics against the model's own axes in
 * work/freud-anim/fk-check.mjs rather than by eye: with these signs the ankle moves forward fast
 * over ~40% of the cycle (swing) and drifts back over 60% (stance), the human split; the reversed
 * set plays the gait backwards while staying symmetric, which is how a rig moonwalks.
 *
 * `scale` trims every joint together so the walk can be made gentler without changing its shape.
 */
export function poseWalk(rig: FreudRig, rest: RestPose, phase: number, scale = 0.78): void {
  const set = (name: string, x: number, y = 0, z = 0): void => {
    const bone = rig.bones.get(name);
    if (!bone) return;
    EULER.set(x, y, z, 'XYZ');
    bone.quaternion.copy(rest.get(name)!).multiply(Q.setFromEuler(EULER));
  };
  const L = phase % 1;
  const R = (phase + 0.5) % 1;              // the other leg is exactly half a cycle behind

  for (const [side, p] of [['L', L], ['R', R]] as const) {
    set(`hip.${side}`, 0, 0, gait(GAIT_HIP, p) * scale);
    set(`knee.${side}`, 0, 0, -gait(GAIT_KNEE, p) * scale);
    set(`ankle.${side}`, 0, 0, gait(GAIT_ANKLE, p) * scale);
  }

  /**
   * Arms counter-swing the legs about the same sagittal axis (z): the left arm goes with the RIGHT
   * leg. Amplitudes are a small fraction of the hip's -- the arms hang inside wide coat sleeves, and
   * beyond a small arc the 2 mm sleeve surface folds over itself under linear blend skinning. The
   * right hand holds a cigar forward, so it keeps half the free arm's swing -- a held object does
   * not flail.
   */
  const ARM = { freeShoulder: { gain: 0.16, max: 0.06 }, freeElbow: { gain: 0.10, max: 0.03 },
                heldShoulder: { gain: 0.08, max: 0.03 }, heldElbow: { gain: 0.05, max: 0.015 } } as const;
  const armL = gait(GAIT_HIP, R) - GAIT_HIP.dc;
  const armR = gait(GAIT_HIP, L) - GAIT_HIP.dc;
  set('shoulder.L', 0, 0, limitAngle(armL * ARM.freeShoulder.gain, ARM.freeShoulder.max));
  set('elbow.L', 0, 0, limitAngle(Math.max(0, armL) * ARM.freeElbow.gain, ARM.freeElbow.max));
  set('shoulder.R', 0, 0, limitAngle(armR * ARM.heldShoulder.gain, ARM.heldShoulder.max));
  set('elbow.R', 0, 0, limitAngle(Math.max(0, armR) * ARM.heldElbow.gain, ARM.heldElbow.max));

  // Pelvis and shoulder girdle turn opposite ways about the vertical, spread along the spine.
  const twist = Math.sin(2 * Math.PI * L);
  set('hips', 0, -twist * 0.07);
  set('spine.01', 0, twist * 0.03);
  set('spine.02', 0, twist * 0.04);
  set('chest', 0, twist * 0.045);
  set('shoulders', 0, twist * 0.04);
  set('head', 0, -twist * 0.03);

  // The pelvis drops twice per stride, once under each leg's load. 0.006 m, scaled from the
  // girl-character's measured 0.016 m by leg length (0.30 m hip height here vs 0.88 m there).
  const restY = rig.root.userData.restY as number | undefined;
  if (restY === undefined) rig.root.userData.restY = rig.root.position.y;
  rig.root.position.y = (rig.root.userData.restY as number)
    - (0.5 - 0.5 * Math.cos(4 * Math.PI * L)) * 0.006;
  rig.root.updateMatrixWorld(true);
}

/** A slow idle so the demo is not motionless: breathing on the spine chain, a slight sway. */
export function poseIdle(rig: FreudRig, rest: RestPose, phase: number): void {
  const t = phase * Math.PI * 2;
  const breathe = Math.sin(t);
  const set = (name: string, x: number, y = 0, z = 0): void => {
    const bone = rig.bones.get(name);
    if (!bone) return;
    EULER.set(x, y, z, 'XYZ');
    bone.quaternion.copy(rest.get(name)!).multiply(Q.setFromEuler(EULER));
  };
  // Sagittal breathing bend is about z in this frame (the axis that pitches a downward limb).
  set('spine.01', 0, 0, -breathe * 0.008);
  set('spine.02', 0, 0, -breathe * 0.008);
  set('chest', 0, 0, -breathe * 0.012);
  set('shoulders', 0, 0, -breathe * 0.006);
  set('head', 0, Math.sin(t * 0.5) * 0.045, -breathe * 0.010);
  set('shoulder.L', 0, 0, breathe * 0.012);
  set('shoulder.R', 0, 0, breathe * 0.010);
  const restY = rig.root.userData.restY as number | undefined;
  if (restY === undefined) rig.root.userData.restY = rig.root.position.y;
  rig.root.position.y = (rig.root.userData.restY as number) + breathe * 0.002;
  rig.root.updateMatrixWorld(true);
}
