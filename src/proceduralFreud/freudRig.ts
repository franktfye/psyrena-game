/**
 * A procedural skeleton, geodesic-baked skin and walk/idle cycle for the freud demo.
 *
 * THIS PART IS GENUINELY CODE, with no alternative: the baseline GLB carries a 53-joint Tripo skin
 * (skinCount 1, animationCount 0) which the pipeline contract does NOT copy -- every joint position,
 * capsule radius, weight and pose here is computed from measurements of the built model or from a
 * cited gait dataset.
 *
 * THE FRAME. The surface data is authored in the GLB's own frame: height +Y, arm span along Z, and
 * the figure faces +X (toes reach x +0.083 at sole level; the beard reads x +0.083 at y 0.88-0.92).
 * Character LEFT is -Z: the forward-held hand with the cigar measures at +Z and reads on the
 * viewer's left -- the character's right -- in the front capture (work/cmp/pipeline-check-freud/
 * front.png). createFreudModel rotates the group -pi/2 about Y, which maps source +X to world +Z.
 * Everything below -- joints, weights, gait signs -- works in the SOURCE frame, and the group
 * rotation carries the animated result to world unchanged.
 *
 * JOINTS COME FROM THE MODEL'S OWN BOUNDS, never from fractions of figure height typed in by hand.
 * The measured table (work/freud-anim/measure*.py against work/freud-gates/meshes.json, 428,110
 * verts, bounds x [-0.1138, 0.1145] y [-0.0022, 1.0009] z [-0.2089, 0.2089]):
 *
 *     soles        y -0.002..0.04     foot extends to x +0.083; ankle at the boot top, y 0.05
 *     legs         y  0.04..0.32      straight tubes, centres z ±0.065..0.089; knee midway, y 0.17
 *     coat hem     y  0.32..0.34      crotch gap between the legs closes at y 0.32
 *     coat/torso   y  0.34..0.82      x half-extent ~0.10; belly front x +0.09 at y 0.48-0.66
 *     arms         hang DOWN (not a T-pose): shoulder (z ±0.100, y 0.700) -> elbow (z ±0.143,
 *                    y 0.615) -> wrist (z ±0.185, y 0.530) -> hand tip (z ±0.206, y ~0.51);
 *                    right hand held forward, x up to +0.11 at y 0.44-0.51
 *     neck         y  0.85            z half-width minimum 0.060 at y 0.86-0.88
 *     head         y  0.86..1.00      centre x +0.005
 *
 * SKINNING IS MANDATORY: the figure is one merged mesh spanning every joint, so no rigid rotation
 * can swing an arm. Weights are baked offline (skinData.ts et al.) by geodesic voxel binding
 * (forge/stage5_rig/geodesic_skinning.py; Dionne & de Lasa, SCA 2013) with capsule radii from the
 * measured part widths and a height-band allow-list -- the single merged region has no part list to
 * key on, so the allow-list is per height band: legs below the hem (y < 0.34, side by z sign),
 * head/neck above the shoulders (y >= 0.83), trunk + same-side arm chain between, with arm bones
 * barred below y 0.42 so the coat hem never follows a wrist. The baked stream passed
 * forge/stage5_rig/validate_rig_payload.py before any THREE.Skeleton was constructed from it.
 */
import * as THREE from 'three';

export type FreudJoint = {
  name: string;
  parent: string | null;
  /** Bind-pose position in the source frame, metres. */
  head: readonly [number, number, number];
  /** Segment tip: the first child's joint, or a measured leaf tip (crown, hand, toe). */
  tip: readonly [number, number, number];
  /** Capsule radius, metres, from the measured half-widths (torso x ~0.10, neck z 0.06, leg z 0.04). */
  radius: number;
};

